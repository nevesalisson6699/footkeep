/**
 * Retorna clubes de determinado estado da federação.
 * @param {string} state Sigla da UF (ex: 'SP', 'RJ', 'MG', 'RS', 'PR')
 */
export function getClubsByState(state) {
  return CLUBS_2026.filter(c => c.state === state);
}
